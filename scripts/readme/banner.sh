# Writes the README's images into the folder $1.
generate() {
  banner_svg >"$1/banner.svg"
  cp "$references/pose-awake-left.png" "$1/cat.png"
}

scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
generate "$scratch"

if [[ $mode == write ]]; then
  mkdir -p "$assets"
  for file in banner.svg cat.png; do
    mv "$scratch/$file" "$assets/$file"
  done
  exit 0
fi

stale=0
for file in banner.svg cat.png; do
  if ! cmp -s "$scratch/$file" "$assets/$file"; then
    echo "README images: $assets/$file differs from what $references gives" >&2
    stale=1
  fi
done
if ((stale)); then
  echo "Regenerate them with scripts/readme/banner.sh" >&2
fi
exit "$stale"
