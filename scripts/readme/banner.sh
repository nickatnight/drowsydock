#!/usr/bin/env bash
# Builds the README's images in docs/readme/ from the pose snapshot references, which CatRenderer
# drew (ADR 0016), so the README shows the real cat.
#
#   scripts/readme/banner.sh          write docs/readme/banner.svg and docs/readme/cat.png
#   scripts/readme/banner.sh --check  exit 1 if either differs from what the references give
#
# banner.svg is a 16 s loop: the battery drains past the default thresholds (50, 30, 20, 10) while
# the cat goes from awake to asleep and the Dock nods off, then a charger plugs in and the cat
# wakes. It uses CSS animation only and embeds the PNGs, so GitHub can show it through <img>.
# With reduced motion it shows the asleep frame, still.
# README_REFERENCES and README_ASSETS override the two folders, for the README check's self-test.
set -euo pipefail
cd "$(dirname "$0")/../.."
export LC_ALL=C

references="${README_REFERENCES:-Tests/DrowsyDockTests/Snapshots}"
assets="${README_ASSETS:-docs/readme}"
mode="${1:-write}"
case "$mode" in
  write | --check) ;;
  *)
    echo "usage: scripts/readme/banner.sh [--check]" >&2
    exit 2
    ;;
esac

loop=16

# Converts a time in seconds into the loop's keyframe percentage.
percent() {
  awk -v t="$1" -v loop="$loop" 'BEGIN { printf "%.6g%%", t * 100 / loop }'
}

# keyframes NAME PROPERTY TIME:VALUE...: one @keyframes rule, with times in seconds.
keyframes() {
  local name="$1" property="$2" pair
  shift 2
  printf '@keyframes %s {' "$name"
  for pair in "$@"; do
    printf ' %s { %s: %s }' "$(percent "${pair%%:*}")" "$property" "${pair#*:}"
  done
  printf ' }\n'
}

add() {
  awk -v a="$1" -v b="$2" 'BEGIN { printf "%.6g", a + b }'
}

# shown NAME FROM TO: an opacity rule, 1 from FROM to TO with 0.15 s fades. FROM > TO wraps
# around the loop's end.
shown() {
  local name="$1" from="$2" to="$3" fade=0.15
  if awk -v a="$from" -v b="$to" 'BEGIN { exit !(a < b) }'; then
    keyframes "$name" opacity 0:0 "$from:0" "$(add "$from" "$fade"):1" "$(add "$to" -"$fade"):1" \
      "$to:0" "$loop:0"
  else
    keyframes "$name" opacity 0:1 "$(add "$to" -"$fade"):1" "$to:0" "$from:0" \
      "$(add "$from" "$fade"):1" "$loop:1"
  fi
}

# The battery's fill is a 210-unit dashed line; the dash offset hides the empty part.
level() {
  awk -v p="$1" 'BEGIN { printf "%.6gpx", 210 * (100 - p) / 100 }'
}

png() {
  printf 'data:image/png;base64,'
  base64 <"$references/$1" | tr -d '\n'
}

# The timeline, in seconds. Each drain takes 0.5 s and the new pose fades in over its last
# 0.25 s, crossing the threshold on the way.
banner_css() {
  keyframes level stroke-dashoffset "0:$(level 80)" "2.5:$(level 80)" "3:$(level 40)" \
    "5:$(level 40)" "5.5:$(level 25)" "7.5:$(level 25)" "8:$(level 15)" "10:$(level 15)" \
    "10.5:$(level 5)" "15:$(level 5)" "15.75:$(level 80)" "16:$(level 80)"
  keyframes charge stroke 0:#34c759 0.5:#34c759 0.51:#6b7383 13.25:#6b7383 13.26:#34c759 \
    16:#34c759
  keyframes plug transform 0:none 0.5:translateX\(60px\) 12.75:translateX\(60px\) 13.25:none \
    16:none
  shown bolt 13.25 0.5
  keyframes base opacity 0:1 3:1 3.01:0 16:0
  keyframes drowsy opacity 0:0 2.75:0 3:1 5.5:1 5.51:0 16:0
  keyframes yawning opacity 0:0 5.25:0 5.5:1 8:1 8.01:0 16:0
  keyframes nodding opacity 0:0 7.75:0 8:1 10.5:1 10.51:0 16:0
  keyframes asleep opacity 0:0 10.25:0 10.5:1 13.5:1 13.51:0 16:0
  keyframes waking opacity 0:0 13.25:0 13.5:1 16:1
  keyframes stretch transform 0:none 13.5:none "13.75:scale(0.97, 1.06)" 14.1:none 16:none
  keyframes sparkle transform 0:scale\(0\) 13.6:scale\(0\) 13.9:scale\(1.3\) 14.5:scale\(1\) \
    14.9:scale\(0\) 16:scale\(0\)
  # CrowdEffectNode: each icon dims to 0.35 black for 0.3 s and puffs a "z" that drifts up 24 pt
  # and grows from 0.5 to 1.1 over 1 s; CrowdWave starts each icon 0.15 s after the last.
  keyframes dim opacity 0:0 10.5:0 10.59:0.35 10.68:0.35 10.8:0 16:0
  keyframes puff opacity 0:0 10.5:0 10.65:1 11.1:1 11.5:0 16:0
  keyframes drift transform "0:scale(0.5)" "10.5:scale(0.5)" \
    "11.5:translate(6.4px, -38.4px) scale(1.1)" "16:translate(6.4px, -38.4px) scale(1.1)"
  shown s80d 0.5 3
  shown s40 3 5.5
  shown s25 5.5 8
  shown s15 8 10.5
  shown s5 10.5 13.25
  shown s5w 13.25 15.25
  shown s80c 15.5 0.5
}

